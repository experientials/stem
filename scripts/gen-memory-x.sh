#!/bin/sh
# Generate the per-chip linker memory maps  prod/memory-<chip>.x  from TI's authoritative device
# linker scripts (msp430<chip>.ld), so RAM/FRAM origins+lengths are never hand-transcribed.
#
# WHY this exists (and what it does NOT generate):
#   - RAM + FRAM(→ROM) regions ARE mechanical facts of the silicon → copied straight from TI's .ld.
#   - VECTORS is NOT in TI's layout form: TI defines the full hardware vector space (VECT0=0xFFA2…),
#     but `msp430-rt` wants a region sized to the PAC's *actual* interrupt count, ending at 0x10000,
#     and it ASSERTs that at link time (link.x: ORIGIN(VECTORS)+LENGTH(VECTORS)==0x10000 AND the
#     .vector_table must exactly fill it). So VECTORS is an msp430-rt/PAC property — we emit the
#     current no-`rt` default (16-word table) and record the PAC-derived origin to switch to when the
#     PAC `rt` feature + real ISRs land. `scripts/lint-memory-x.sh` cross-checks that against the PAC.
#
# Source of truth: TI MSP430-GCC support files (CCS install or the standalone msp430-gcc package).
# Set MSP430_LD_DIR to override the auto-detected location.
#
# Usage: scripts/gen-memory-x.sh            # regenerate all four
set -eu

LD_DIR="${MSP430_LD_DIR:-}"
if [ -z "$LD_DIR" ]; then
  for d in \
    "/Applications/ti/ccs2101/ccs/ccs_base/msp430/include_gcc" \
    "$HOME/Library/Mobile Documents/com~apple~CloudDocs/Downloads/msp430-gcc/include" \
    "/opt/msp430-gcc/include"; do
    if [ -f "$d/msp430fr2355.ld" ]; then LD_DIR="$d"; break; fi
  done
fi
[ -n "$LD_DIR" ] || { echo "gen-memory-x: no TI .ld dir found — set MSP430_LD_DIR to your msp430-gcc include/ or CCS include_gcc/" >&2; exit 1; }
echo "==> TI linker scripts: $LD_DIR"

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/prod"

# Pull "ORIGIN = 0x…" / "LENGTH = 0x…" out of a named region line inside the MEMORY{} block.
field() { # <ld> <region-awk-match> <ORIGIN|LENGTH>
  awk '/^MEMORY/,/^}/' "$1" | awk "$2 {print; exit}" | sed -nE "s/.*$3 *= *(0x[0-9A-Fa-f]+).*/\1/p"
}

emit() { # <chip> <note>
  chip="$1"; note="$2"
  ld="$LD_DIR/msp430$chip.ld"
  [ -f "$ld" ] || { echo "gen-memory-x: missing $ld" >&2; exit 1; }
  ram_o=$(field "$ld" '/^[ \t]*RAM[ \t]*:/' ORIGIN)
  ram_l=$(field "$ld" '/^[ \t]*RAM[ \t]*:/' LENGTH)
  fram_o=$(field "$ld" '/FRAM *\(/' ORIGIN)
  fram_l=$(field "$ld" '/FRAM *\(/' LENGTH)
  [ -n "$ram_o" ] && [ -n "$ram_l" ] && [ -n "$fram_o" ] && [ -n "$fram_l" ] || {
    echo "gen-memory-x: failed to parse RAM/FRAM from $ld" >&2; exit 1; }
  ram_kb=$(( ram_l / 1024 ))
  fram_end=$(printf '0x%04X' $(( fram_o + fram_l - 1 )))
  # fr2433's map lives with its binary (modules/expander/, S2a reorg); the dual families stay in prod/.
  if [ "$chip" = fr2433 ]; then out="$ROOT/modules/expander/memory-$chip.x"; emitter="modules/expander/build.rs"; else out="$OUT/memory-$chip.x"; emitter="prod/build.rs"; fi
  cat > "$out" <<EOF
/* GENERATED by scripts/gen-memory-x.sh from TI's msp430$chip.ld — do NOT hand-edit.
 * $note
 * RAM/ROM(FRAM) are copied verbatim from the TI device linker script (the authoritative memory map).
 * Emitted to OUT_DIR as memory.x by $emitter. */
MEMORY
{
  RAM     : ORIGIN = $ram_o, LENGTH = $ram_l   /* ${ram_kb} KB SRAM */
  ROM     : ORIGIN = $fram_o, LENGTH = $fram_l   /* program FRAM (main window), END $fram_end */
  /* VECTORS: msp430-rt's current (no-\`rt\`) default is a 16-word table ending at 0x10000. When the PAC
     \`rt\` feature + real ISRs land, set ORIGIN to the chip's lowest interrupt vector (see
     scripts/lint-memory-x.sh / the chip's PAC); msp430-rt's link.x ASSERT enforces the exact size. */
  VECTORS : ORIGIN = 0xFFE0, LENGTH = 0x0020
}

/* Checksum region (single source of truth): prod/src/post.rs reads these as extern symbols to CRC the
   program FRAM per sector — DESIGN.md console log. */
PROVIDE(__fram_start = ORIGIN(ROM));
PROVIDE(__fram_size  = LENGTH(ROM));
EOF
  echo "    wrote $out   (RAM $ram_o/$ram_l, ROM $fram_o/$fram_l)"
}

echo "==> generating prod/memory-<chip>.x"
emit fr2155 "MSP430FR2155 — production dual-I2C baseline. Shares its map with FR2355 (verify: diff memory-fr2155.x memory-fr2355.x)."
emit fr2355 "MSP430FR2355 — dev LaunchPad (MSP-EXP430FR2355), a SAC superset of FR2155 with the SAME memory map."
emit fr2476 "MSP430FR247x (FR2476/FR2475) dev part. FR2476 has 64 KB FRAM but only the lower 32 KB window (0x8000-0xFF7F) is linked (no large-memory model); 8 KB SRAM."
emit fr2433 "MSP430FR2433 — single-I2C slave-only expander. 15 KB program FRAM; the 512 B info FRAM (0x1800) is a separate data region, not mapped here."

echo "Done. Validate with:  scripts/lint-memory-x.sh"
